/* 방 테두리 벽을 쉽게 만들어주는 도우미.
   똑같은 벽 네 개를 매번 쓰기 귀찮으니까 함수로 만들었어! */
function roomWalls(x, y, w, h, t = 24) {
  return [
    { x: x,         y: y,         w: w, h: t },   // 위쪽 벽
    { x: x,         y: y + h - t, w: w, h: t },   // 아래쪽 벽
    { x: x,         y: y,         w: t, h: h },   // 왼쪽 벽
    { x: x + w - t, y: y,         w: t, h: h }    // 오른쪽 벽
  ];
}


